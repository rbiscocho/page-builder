<?php

declare(strict_types=1);

namespace PageBuilder\FilamentPageBuilder\Console;

use Illuminate\Console\Command;
use PageBuilder\FilamentPageBuilder\Support\TokenMap;

class TailwindSafelistCommand extends Command
{
    protected $signature = 'page-builder:tailwind-safelist
                            {--path= : Output path (default from config)}';

    protected $description = 'Generate a Tailwind v4 @source inline(...) safelist CSS file from TokenMap';

    public function handle(): int
    {
        $path = $this->option('path')
            ?: config('filament-page-builder.safelist_path', 'resources/css/page-builder-safelist.css');

        if (! str_starts_with($path, '/')) {
            $path = base_path($path);
        }

        $classes = TokenMap::allClasses();
        sort($classes);

        $chunks = array_chunk($classes, 40);
        $lines = [
            '/* Auto-generated by page-builder:tailwind-safelist — do not edit */',
            '/* Import this file in your React Tailwind entry CSS */',
            '',
        ];

        foreach ($chunks as $chunk) {
            $quoted = implode(' ', $chunk);
            $lines[] = "@source inline(\"{$quoted}\");";
        }

        $lines[] = '';

        $dir = dirname($path);
        if (! is_dir($dir)) {
            mkdir($dir, 0755, true);
        }

        file_put_contents($path, implode("\n", $lines));

        $this->info('Wrote '.count($classes).' classes to '.$path);

        return self::SUCCESS;
    }
}
